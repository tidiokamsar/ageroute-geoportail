-- INDEX GIST PLANAIRE SUR troncons.geom (scenario A15 : « rattachement < 300 ms p95 »)
--
-- `troncons` ne portait qu'un index GiST sur l'EXPRESSION `geom::geography` (migration
-- `20260901170000`), qui sert les distances en metres. Mais la requete de candidats du rattachement
-- ponctuel (`geo/appariement.ts`) trie par `t.geom <-> point` (plus proche voisin) et filtre par
-- `t.geom && emprise` : deux operateurs PLANAIRES, qu'un index sur l'expression geography ne sert
-- pas. Chaque rattachement sans emprise balayait donc la table et la triait.
--
-- MESURE du 22/10/2026 (banc `prisma/tests/appariement.bench.sql`, 261 387 troncons synthetiques,
-- le volume de production) :
--   - tout le reseau, sans emprise : mediane 376,7 ms, p95 831,9 ms SANS cet index -- A15 echoue ;
--                                    mediane 0,55 ms,  p95 0,85 ms AVEC ;
--   - reseau classe, emprise 2 km  : p95 3,54 ms sans, 1,20 ms avec ;
--   - premier candidat identique avec et sans index sur les 300 positions (le resultat n'en depend pas).
--
-- POSE : 3,6 s sur 261 387 lignes sur le poste de developpement. `migrate deploy` execute dans une
-- transaction, donc sans CONCURRENTLY : les ECRITURES sur `troncons` attendent le temps de la pose.
-- A faire en fenetre de maintenance. Avant deploiement, verifier qu'aucun index GiST planaire
-- equivalent n'existe deja en production sous un autre nom (prerequis 9 du suivi d'execution) :
-- sinon, ce serait un doublon.
--
-- NATURE : additive. Un index. Aucune ligne touchee.

CREATE INDEX IF NOT EXISTS "troncons_geom_gist" ON "troncons" USING gist ("geom");
